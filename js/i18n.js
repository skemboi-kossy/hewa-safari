export const DAY_NAMES = {
    en: [ "Sun", "Mon", "Tue", "Wed", "Thu", "Fri", "Sat"],
    sw: ["Jumapili", "Jumatatu", "Jumanne", "Jumatano", "Alhamisi", "Ijumaa", "Jumamosi"],
};


// Returns a translated string,filling {placeholders} from values.
export function t(lang, key, values = {}) {
    const template = (STRINGS[lang] && STRINGS[lang][key]) || STRINGS.en[key] || key;
    return template.replace(/\{(\w+)\}/g, (match, name) => name in values ? String(values[name]) : match);
}
   
export function dayName(lang, isoDate) {
    const day = new Date(`${isoDate}T00:00:00`).getDay();
    return (DAY_NAMES[lang] || DAY_NAMES.en)[day];
}
